class PgCursor:
    def __init__(self, cursor, lastrowid=None):
        self._cursor = cursor
        self.lastrowid = lastrowid
        self.rowcount = cursor.rowcount
    def fetchone(self): return self._cursor.fetchone()
    def fetchall(self): return self._cursor.fetchall()
    def __iter__(self): return iter(self._cursor)

class PgConnection:
    def __init__(self):
        import psycopg
        from psycopg.rows import dict_row
        self._conn = psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=12)
    def execute(self, sql, params=()):
        # The existing application's queries use SQLite positional placeholders.
        sql = sql.replace('?', '%s').replace("date('now')", 'CURRENT_DATE')
        is_insert = bool(re.match(r'\s*INSERT\s+INTO\s+', sql, re.I))
        if is_insert and 'RETURNING' not in sql.upper():
            sql = sql.rstrip().rstrip(';') + ' RETURNING id'
        cur = self._conn.execute(sql, params)
        last_id = cur.fetchone()['id'] if is_insert else None
        return PgCursor(cur, last_id)
    def executescript(self, script):
        for statement in script.split(';'):
            statement = statement.strip()
            if statement:
                statement = re.sub(r'INTEGER PRIMARY KEY AUTOINCREMENT', 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', statement, flags=re.I)
                self._conn.execute(statement)
    def commit(self): self._conn.commit()
    def rollback(self): self._conn.rollback()
    def close(self): self._conn.close()

